"""Build the horizon-equivalence CPU kernel (id mauricew/glia-cpu-traj).

CPU kernels do not draw on GPU quota (we have 0.03h of GPU left until the Sunday
refresh). The metadata deliberately carries NO `machine_shape`: that key forces a GPU
even when enable_gpu is false, which would burn quota from a kernel believed to be free.
The builder asserts it is absent.
"""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))
FILES = {
    "src/lever.py": os.path.join(ROOT, "src", "lever.py"),
    "src/cpu_horizon.py": os.path.join(ROOT, "src", "cpu_horizon.py"),
    "src/cpu_trajectory.py": os.path.join(ROOT, "src", "cpu_trajectory.py"),
    "s1_pairs.json": os.path.join(ROOT, "s1_pairs.json"),
}
for name, path in FILES.items():
    assert os.path.exists(path), f"missing payload file {name} -> {path}"
    assert os.path.getsize(path) < 5_000_000, f"payload file unexpectedly large: {name}"
payload = {n: base64.b64encode(open(p, "rb").read()).decode() for n, p in FILES.items()}

MAIN = '''"""GENERATED by build_cpu.py - trajectory-equivalence horizon (CPU)."""
import base64, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    p = os.path.join(root, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(base64.b64decode(b64))

print("cpu kernel: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "transformers==5.22.1"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu",
      "| threads:", os.environ.get("N_THREADS", "4"), flush=True)

subprocess.run([sys.executable, os.path.join(root, "src", "cpu_trajectory.py")],
               check=True, env=dict(os.environ, OUT_DIR="/kaggle/working",
                                    PYTHONPATH=os.path.join(root, "src"),
                                    ALPHAS="1.0 1.5 2.0", ROLLOUT="1024",
                                    DEADLINE_S="5400", N_THREADS="4"))
'''

src = MAIN.replace("__PAYLOAD__", repr(payload))
out_dir = os.path.join(ROOT, "kernel_cpu")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(src)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/glia-cpu-traj")
meta = {"id": kid, "title": kid.split("/")[-1], "code_file": "main.py",
        "language": "python", "kernel_type": "script",
        "enable_gpu": False, "enable_internet": True, "is_private": True,
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}
assert "machine_shape" not in meta, "machine_shape forces a GPU even with enable_gpu=False"
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"), "| enable_gpu:", meta["enable_gpu"],
      "| machine_shape: absent")
