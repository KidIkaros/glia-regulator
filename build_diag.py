"""Build the diagnostic kernel (GPU, id mauricew/glia-diag-v1). ~5 min of quota."""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))
FILES = {
    "src/glial.py": os.path.join(ROOT, "src", "glial.py"),
    "src/diagnose_context.py": os.path.join(ROOT, "src", "diagnose_context.py"),
    "src/lever.py": os.path.join(ROOT, "src", "lever.py"),
    "src/lever_check.py": os.path.join(ROOT, "src", "lever_check.py"),
    "s1_pairs.json": os.path.join(ROOT, "s1_pairs.json"),
    "gt15.npy": os.path.join(ROOT, "ground_truth", "neurons_L15.npy"),
    "gt19.npy": os.path.join(ROOT, "ground_truth", "neurons_L19.npy"),
    "neurons_L15.npy": os.path.join(ROOT, "ground_truth", "neurons_L15.npy"),
    "neurons_L19.npy": os.path.join(ROOT, "ground_truth", "neurons_L19.npy"),
    "loopdir_L15.npy": os.path.join(ROOT, "ground_truth", "loopdir_L15.npy"),
    "loopdir_L19.npy": os.path.join(ROOT, "ground_truth", "loopdir_L19.npy"),
    "proj_L15.npy": os.path.join(ROOT, "ground_truth", "proj_L15.npy"),
    "proj_L19.npy": os.path.join(ROOT, "ground_truth", "proj_L19.npy"),
}
payload = {n: base64.b64encode(open(p, "rb").read()).decode() for n, p in FILES.items()}

MAIN = '''"""GENERATED by build_diag.py - Q1 context-blindness + Q2 gain authority."""
import base64, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    p = os.path.join(root, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(base64.b64decode(b64))

print("gpu kernel: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "transformers==5.22.1"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu", flush=True)

subprocess.run([sys.executable, os.path.join(root, "src", "diagnose_context.py")],
               check=True, env=dict(os.environ, OUT_DIR="/kaggle/working",
                                    PYTHONPATH=os.path.join(root, "src"),
                                    DEADLINE_S="900"))
'''

src = MAIN.replace("__PAYLOAD__", repr(payload))
out_dir = os.path.join(ROOT, "kernel_diag")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(src)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/glia-lever-check")
meta = {"id": kid, "title": kid.split("/")[-1], "code_file": "main.py",
        "language": "python", "kernel_type": "script",
        "enable_gpu": True, "enable_internet": True, "is_private": True,
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"))
