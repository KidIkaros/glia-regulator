"""Build the dose-response kernel (GPU, id mauricew/glia-dose-v1).

Payload is small: the extracted per-layer delta + column indices + the paired problems.
The 1.6 GB edited checkpoint is NOT shipped -- the payload is validated against the live
weights inside the kernel instead (see src/dose_response.py).
"""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))
FILES = {
    "src/lever.py": os.path.join(ROOT, "src", "lever.py"),
    "src/dose_response.py": os.path.join(ROOT, "src", "dose_response.py"),
    "s1_pairs.json": os.path.join(ROOT, "s1_pairs.json"),
}
for name, path in FILES.items():
    assert os.path.exists(path), f"missing payload file {name} -> {path}"
    assert os.path.getsize(path) < 5_000_000, f"payload file unexpectedly large: {name}"
payload = {n: base64.b64encode(open(p, "rb").read()).decode() for n, p in FILES.items()}

MAIN = '''"""GENERATED by build_dose.py - lever dose-response (alpha sweep)."""
import base64, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    p = os.path.join(root, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(base64.b64decode(b64))

print("gpu kernel: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "transformers==5.22.1"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu", flush=True)

subprocess.run([sys.executable, os.path.join(root, "src", "dose_response.py")],
               check=True, env=dict(os.environ, OUT_DIR="/kaggle/working",
                                    PYTHONPATH=os.path.join(root, "src"),
                                    ALPHAS="0 0.5 1.0 1.5 2.0",
                                    N_PROBLEMS="4", MAX_NEW="16384",
                                    DEADLINE_S="5400"))
'''

src = MAIN.replace("__PAYLOAD__", repr(payload))
out_dir = os.path.join(ROOT, "kernel_dose")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(src)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/glia-dose-v1")
meta = {"id": kid, "title": kid.split("/")[-1], "code_file": "main.py",
        "language": "python", "kernel_type": "script",
        "enable_gpu": True, "enable_internet": True, "is_private": True,
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"))
