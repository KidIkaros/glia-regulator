"""Build a CPU-only Kaggle kernel for the glial dry run (no GPU, no quota).

Per the kaggle-experiments skill: a CPU kernel must NOT carry machine_shape, which
forces a T4 allocation and silently burns GPU quota.
"""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))

FILES = {
    "src/glial.py": os.path.join(ROOT, "src", "glial.py"),
    "src/dryrun.py": os.path.join(ROOT, "src", "dryrun.py"),
}
payload = {n: base64.b64encode(open(p, "rb").read()).decode() for n, p in FILES.items()}

MAIN = '''"""GENERATED by build.py - CPU dry run of the glial integration."""
import base64, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    p = os.path.join(root, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(base64.b64decode(b64))

print("cpu kernel: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "transformers==5.22.1"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu", flush=True)
subprocess.run([sys.executable, os.path.join(root, "src", "dryrun.py")],
               check=True, env=dict(os.environ, OUT_DIR="/kaggle/working",
                                    PYTHONPATH=os.path.join(root, "src")))
'''

src = MAIN.replace("__PAYLOAD__", repr(payload))
out_dir = os.path.join(ROOT, "kernel_dry")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(src)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/glia-dryrun")
meta = {
    "id": kid, "title": kid.split("/")[-1], "code_file": "main.py",
    "language": "python", "kernel_type": "script",
    "enable_gpu": False,          # CPU: free, no quota
    "enable_internet": True, "is_private": True,
    "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
    "model_sources": [],
}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"), "| enable_gpu:", meta["enable_gpu"])
