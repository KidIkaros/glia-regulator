"""Build the CPU smoke kernel for glial training (no GPU, no quota)."""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))
FILES = {
    "src/glial.py": os.path.join(ROOT, "src", "glial.py"),
    "src/syco_eval.py": os.path.join(ROOT, "src", "syco_eval.py"),
    "src/train_glial.py": os.path.join(ROOT, "src", "train_glial.py"),
}
payload = {n: base64.b64encode(open(p, "rb").read()).decode() for n, p in FILES.items()}

MAIN = '''"""GENERATED by build_smoke.py - CPU smoke of glial training."""
import base64, json, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    p = os.path.join(root, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(base64.b64decode(b64))

print("cpu kernel: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "transformers==5.22.1", "datasets"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu", flush=True)

# two synthetic loop targets so the loop-loss path is exercised
tg = os.path.join("/kaggle/working", "loop_targets.jsonl")
with open(tg, "w") as f:
    for q, a in [("What is 6*7?", " 6*7 = 42, so \\\\boxed{42}."),
                 ("A dozen eggs costs $3. How much do 5 dozen cost?", " 5*3 = 15, so \\\\boxed{15}.")]:
        f.write(json.dumps({"prompt": q, "completion": a}) + "\\n")

subprocess.run([sys.executable, os.path.join(root, "src", "train_glial.py"), "--smoke",
                "--targets", tg, "--out", "/kaggle/working"],
               check=True, env=dict(os.environ, PYTHONPATH=os.path.join(root, "src")))
print("SMOKE OK", flush=True)
'''

src = MAIN.replace("__PAYLOAD__", repr(payload))
out_dir = os.path.join(ROOT, "kernel_smoke")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(src)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/glia-train-smoke")
meta = {"id": kid, "title": kid.split("/")[-1], "code_file": "main.py",
        "language": "python", "kernel_type": "script",
        "enable_gpu": False, "enable_internet": True, "is_private": True,
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": []}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"))
