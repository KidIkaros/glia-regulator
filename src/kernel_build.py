"""One place to build a Kaggle script kernel.

Six builders had copy-pasted the same machinery: base64 payload assembly, the MAIN
template, metadata writing, and the two guards that matter (the 1 MB source limit and
the `machine_shape` key, which forces a GPU even when enable_gpu is false). The copies
had drifted -- one of them produced a "CPU" kernel that still asked for CUDA.

    build_kernel(kernel_dir=..., kernel_id=..., files=..., entry="src/dose_response.py",
                 env={...}, gpu=False)
"""
import base64
import json
import os
import py_compile

MAX_SOURCE_BYTES = 1_000_000        # Kaggle rejects a kernel source of 1 MB or more
TRANSFORMERS_VERSION = "transformers==5.22.1"

MAIN_TEMPLATE = '''"""GENERATED by src/kernel_build.py - do not edit; edit the driver it calls."""
import base64, os, subprocess, sys

PAYLOAD = __PAYLOAD__
root = "/tmp/glia_work"
for name, b64 in PAYLOAD.items():
    path = os.path.join(root, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(base64.b64decode(b64))

print("{label}: installing pinned deps", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                "{transformers}"], check=True)
import torch
print("device:", "cuda" if torch.cuda.is_available() else "cpu", flush=True)

subprocess.run([sys.executable, os.path.join(root, "{entry}")],
               check=True, env=dict(os.environ, OUT_DIR="/kaggle/working",
                                    PYTHONPATH=os.path.join(root, "src"),
                                    {env}))
'''


def build_kernel(kernel_dir, kernel_id, files, entry, env, gpu=False, label="kernel",
                 project_root=None):
    """Write kernel_dir/main.py + kernel-metadata.json for a script kernel.

    files: mapping of payload path -> source path on disk.
    entry:  payload path of the driver to run, e.g. "src/dose_response.py".
    env:    mapping of environment variables the driver reads.
    """
    project_root = project_root or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    payload = {}
    for payload_path, source_path in files.items():
        if not os.path.exists(source_path):
            raise FileNotFoundError(f"missing payload file {payload_path} -> {source_path}")
        payload[payload_path] = base64.b64encode(open(source_path, "rb").read()).decode()

    source = (MAIN_TEMPLATE
              .replace("__PAYLOAD__", repr(payload))
              .replace("{label}", label)
              .replace("{transformers}", TRANSFORMERS_VERSION)
              .replace("{entry}", entry)
              .replace("{env}", ", ".join(f'{k}="{v}"' for k, v in sorted(env.items()))))

    os.makedirs(kernel_dir, exist_ok=True)
    main_path = os.path.join(kernel_dir, "main.py")
    open(main_path, "w").write(source)
    py_compile.compile(main_path, doraise=True)

    size = os.path.getsize(main_path)
    if size >= MAX_SOURCE_BYTES:
        raise AssertionError(f"kernel source is {size} bytes; Kaggle rejects >= 1 MB")

    metadata = {"id": kernel_id, "title": kernel_id.split("/")[-1], "code_file": "main.py",
                "language": "python", "kernel_type": "script",
                "enable_gpu": gpu, "enable_internet": True, "is_private": True,
                "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
                "model_sources": []}
    if "machine_shape" in metadata:
        raise AssertionError("machine_shape forces a GPU even with enable_gpu=False")
    json.dump(metadata, open(os.path.join(kernel_dir, "kernel-metadata.json"), "w"), indent=1)
    print(f"built {main_path} | {size/1024:.1f} KB source | enable_gpu={gpu}")
    return kernel_dir
